/**
 * OpenCode tier assets: managed planner/coordinator/worker agent definitions
 * and the runtime model-routing plugin.
 *
 * These are generated into `.opencode/agents/` and `.opencode/plugins/` when
 * the OpenCode tool is configured. The agent files carry the tier contract and
 * the delegation permissions; the plugin re-reads `openspec/models.json` on
 * every delegated prompt so `/opsx:models` selections take effect on
 * subsequent delegations in the same session, without a restart.
 *
 * First installation still needs one host restart (plugin and agent files are
 * read at startup). After that, editing only models.json is live.
 */

/** Managed agent names, matching the tier keys in `openspec/models.json`. */
export const OPENCODE_TIER_AGENTS = {
  planner: 'openspec-planner',
  coordinator: 'openspec-coordinator',
  worker: 'openspec-worker',
} as const;

export type OpenCodeTier = keyof typeof OPENCODE_TIER_AGENTS;

/** The tier each managed agent serves (for the plugin's JSON lookup). */
export const OPENCODE_AGENT_TIER: Record<string, OpenCodeTier> = {
  [OPENCODE_TIER_AGENTS.planner]: 'planner',
  [OPENCODE_TIER_AGENTS.coordinator]: 'coordinator',
  [OPENCODE_TIER_AGENTS.worker]: 'worker',
};

const TIER_MODEL_HINT: Record<OpenCodeTier, string> = {
  planner: 'openai/gpt-6.1-sol',
  coordinator: 'openai/gpt-6.1-sol',
  worker: 'openai/gpt-6-luna',
};

/**
 * Agent file bodies. The `model` frontmatter is only the startup fallback —
 * the routing plugin overrides it per dispatch from `openspec/models.json`.
 */
export function getOpenCodeTierAgentSource(tier: OpenCodeTier): string {
  const name = OPENCODE_TIER_AGENTS[tier];
  const description = {
    planner:
      'OpenSpec planner tier: scope, architecture, dependency decomposition, acceptance criteria, and hard reconciliation. Read-mostly; returns decisions and plans.',
    coordinator:
      'OpenSpec coordinator tier: dispatch, joins, ownership, shared-state updates, and verification of delegated work.',
    worker:
      'OpenSpec worker tier: executes ONE bounded, fully specified unit and returns evidence or a blocker. Never delegates.',
  }[tier];

  const body = {
    planner: `You are the OpenSpec **planner** tier.

You decide *what* is true or in scope: scope, architecture, dependency decomposition, acceptance criteria, and semantic merge or conflict decisions. Return decisions and a plan, not implementation.

Rules:
- Stay read-only unless the task that dispatched you explicitly authorizes one named output file.
- State assumptions and open questions explicitly; never resolve material ambiguity silently.
- Do not delegate to other agents. If the work needs a different tier, say so and return.
- Return: the decision or plan, the reasoning in brief, and any blocker.`,
    coordinator: `You are the OpenSpec **coordinator** tier.

You orchestrate work the planner has already decomposed: dispatch, joining results, serialized updates to shared state, verification of returned work, and workflow transitions.

Rules:
- Dispatch workers with self-contained prompts: goal, absolute paths, context, acceptance criteria, owned files, and a stop condition.
- Fan out independent units; await a producer before its consumer; join every dispatched unit before touching shared state.
- Own task checkboxes and tracking files yourself; workers return evidence.
- Do not delegate to other coordinators or planners unless the dispatching task says to.
- Return: what completed, what failed, and what is blocked.`,
    worker: `You are the OpenSpec **worker** tier.

You execute ONE bounded, fully specified unit and return its result. You are a leaf: you do not delegate.

Rules:
- **Never spawn agents, never invoke other skills, never expand scope.**
- Do exactly what the dispatching prompt specifies. Touch only the files it names.
- Verify completion the way the prompt asks (run the named check, or state the observable result).
- If anything is underspecified, blocked, or contradicts the prompt, STOP and return the blocker with what you found. Do not guess or silently narrow the work.
- Return: the changed-path list (if any), the evidence, or the blocker.`,
  }[tier];

  return `---
description: ${description}
mode: subagent
model: ${TIER_MODEL_HINT[tier]}
---

${body}
`;
}

/**
 * The runtime model-routing plugin. OpenCode 1.x loads local plugins from
 * `.opencode/plugins/` at startup and invokes `chat.message` with a mutable
 * `output.message` before the delegated prompt enters its model loop. Rereading
 * the project's `openspec/models.json` there is what makes `/opsx:models`
 * selections apply to later delegations in the same session.
 */
export function getOpenCodeModelRouterPluginSource(): string {
  return `// OpenSpec agent-tier model router.
// Generated by OpenSpec; safe to regenerate.
//
// Reads <project>/openspec/models.json on every delegated prompt and routes
// the managed tier agents (openspec-planner / openspec-coordinator /
// openspec-worker) to the configured model and reasoning variant. Editing that
// file therefore applies to subsequent delegations without restarting; only
// installing or changing this plugin needs one restart.

import { readFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const AGENT_TIER = {
  '${OPENCODE_TIER_AGENTS.planner}': 'planner',
  '${OPENCODE_TIER_AGENTS.coordinator}': 'coordinator',
  '${OPENCODE_TIER_AGENTS.worker}': 'worker',
};

const MANAGED = new Set(Object.keys(AGENT_TIER));
const states = new Map();
const sessions = new Map();
const transitions = [];
const COOLDOWN = 300000;

function findConfigPath(startDir) {
  let dir = resolve(startDir);
  for (;;) {
    const candidate = join(dir, 'openspec', 'models.json');
    if (existsSync(candidate)) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function readSelections(startDir) {
  const configPath = findConfigPath(startDir);
  if (!configPath) return null;
  try {
    const parsed = JSON.parse(readFileSync(configPath, 'utf-8'));
    return parsed && parsed.tiers && typeof parsed.tiers === 'object' ? { tiers: parsed.tiers, identity: resolve(configPath) } : null;
  } catch {
    return null;
  }
}

function fingerprint(selection) { return JSON.stringify([selection.model, selection.effort, selection.secondary?.model ?? null, selection.secondary?.effort ?? null]); }
function stateFor(key) { let s = states.get(key); if (!s) { s = { streak: 0, category: null, retry: null, until: 0, lease: false }; states.set(key, s); } return s; }
function classify(value) {
  if (value === 401 || value === 403) return 'authentication';
  if (value === 402) return 'credits-quota';
  if (value === 404) return 'unavailable-model';
  if (value === 429) return 'rate-limit';
  if (typeof value === 'number' && value >= 500 && value <= 599) return 'server';
  const table = { 'insufficient credits': 'credits-quota', 'quota exceeded': 'credits-quota', 'model not found': 'unavailable-model', 'model_not_found': 'unavailable-model', 'overloaded': 'overload', 'overload': 'overload', 'timeout': 'transport', 'connection failed': 'transport', 'network error': 'transport' };
  return table[String(value ?? '').toLowerCase()] || null;
}
function emit(slot, pair, category, state) { transitions.push({ slot, model: pair.model, effort: pair.effort, category: category || null, cooldown: state.until > Date.now() ? state.until : null, probe: state.lease }); }
function record(scope, category, retry, success) {
  const s = stateFor(scope.key);
  if (success) { s.streak = 0; s.category = null; s.retry = null; if (scope.probe) { s.until = 0; s.lease = false; } return; }
  if (!category) { s.streak = 0; s.category = null; s.retry = null; if (scope.probe) s.lease = false; return; }
  if (retry) { if (s.retry && s.retry !== category) { s.streak = 0; s.category = null; } s.retry = category; return; }
  const retried = !!s.retry;
  if (retried && s.retry !== category) { s.streak = 0; s.category = null; }
  else if (s.category !== category) { s.streak = 0; s.category = category; }
  s.retry = null;
  s.streak++;
  if ((retried || s.streak >= 2) && scope.slot === 'primary') { s.until = Date.now() + COOLDOWN; s.streak = 0; emit('secondary', scope.primary, category, s); }
  if (scope.probe) { s.lease = false; if (['authentication','credits-quota','unavailable-model','transport','rate-limit','overload','server'].includes(category)) s.until = Date.now() + COOLDOWN; }
}

export const OpenSpecModelRouter = async () => ({
  getTransitions() { return transitions; },
  async 'chat.message'(input, output) {
    const message = output && output.message;
    if (!message || message.role !== 'user') return;
    const tier = AGENT_TIER[message.agent];
    if (!tier || !MANAGED.has(message.agent)) return;

    const config = readSelections(process.cwd());
    const selection = config && config.tiers[tier];
    if (!selection || typeof selection.model !== 'string' || selection.model.trim() === '') return;

    const primary = { model: selection.model, effort: selection.effort || 'default' };
    const secondary = selection.secondary && typeof selection.secondary.model === 'string' ? { model: selection.secondary.model, effort: selection.secondary.effort || 'default' } : null;
    let pair = primary; let slot = 'primary'; let probe = false; let key;
    if (secondary) {
      key = JSON.stringify([resolve(config.identity), tier, fingerprint(selection)]);
      const s = stateFor(key); const now = Date.now();
      if (s.until > now || s.lease) { pair = secondary; slot = 'secondary'; }
      else if (s.until && s.until <= now) { s.lease = true; probe = true; }
      sessions.set(String(input?.sessionID || ''), { key, tier, primary, secondary, slot, probe });
    }
    const slash = pair.model.indexOf('/');
    if (slash <= 0 || slash === pair.model.length - 1) return;
    const next = { providerID: pair.model.slice(0, slash), modelID: pair.model.slice(slash + 1) };
    if (pair.effort && pair.effort !== 'default') next.variant = pair.effort;
    message.model = next;
    if (secondary) emit(slot, pair, null, stateFor(key));
  },
  async event(input) {
    const props = input?.event?.properties || input?.properties || {};
    const sessionID = props.sessionID || input?.event?.sessionID;
    const scope = sessions.get(String(sessionID || ''));
    if (!scope) return;
    const type = input?.event?.type || input?.type || '';
    if (type.includes('status')) {
      const status = props.status || props;
      if (status?.retry) record(scope, classify(status.code || status.message), true, false);
      if (status?.completed || status?.status === 'completed') record(scope, null, false, true);
    } else if (type.includes('error') || props.error) {
      const error = props.error || props;
      record(scope, classify(error.statusCode || error.status || error.code) || classify(error.message), false, false);
    }
  },
});
`;
}
